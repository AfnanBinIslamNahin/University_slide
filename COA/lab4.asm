org 100h

.MODEL SMALL
.STACK 100H
.DATA
HELLO_MSG DB 'Hello World' ,0Dh, 0Ah, 24h
BYE_MSG DB 'Bye World',0Dh, 0Ah, 24h

COUNT DB 0

.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX
    
 PRINT_LOOP:
 
 MOV AH,09H
 LEA DX,HELLO_MSG
 INT 21H
 
 INC COUNT
 CMP COUNT,5
 JE PRINT_BYE
 JMP PRINT_LOOP
 
 PRINT_BYE:
 
 MOV AH,09H
 LEA DX, BYE_MSG
 INT 21H
 
 MOV AH,4CH
 
 INT 21H
 
 MAIN ENDP
END MAIN
